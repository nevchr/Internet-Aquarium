await (await exportEvent).saveAs('test-results/export.json');
await page.getByRole('button', { name: '500 fish', exact: true }).click();
await page.getByRole('button', { name: 'Close settings' }).click();
await page.waitForFunction(() => document.querySelector('canvas.aquarium-canvas')?.dataset.fishCount === '500');
await page.waitForTimeout(4000);
